import type { ApiKeyStatus, Plan, AccountStatus } from "@prisma/client";

/**
 * The exact selected shapes `apiKeyAuth` puts on the context (KEY_SELECT) —
 * NOT the full Prisma models. Declaring the full models was a type-lie:
 * `c.set` rejected the narrower value (TS2769) and any consumer reading an
 * unselected column (e.g. createdAt) would get `undefined` at runtime.
 */
/**
 * Platform identity only (07-identity §II) — reputation/roles/profile live
 * here. Billing (plan/creditBalance) moved to ApiClient — see
 * docs/superpowers/specs/2026-08-05-api-client-model-design.md.
 */
export type AuthedAccount = {
  id: string;
  status: AccountStatus;
};
/** The billing identity — every ApiClient has exactly one Account (the reverse is optional). */
export type AuthedApiClient = {
  id: string;
  accountId: string;
  plan: Plan;
  creditBalance: number;
};
export type AuthedApiKey = {
  id: string;
  status: ApiKeyStatus;
  apiClient: AuthedApiClient & { account: AuthedAccount };
};

/**
 * Hono context variables set by middleware.
 * - requestId: UUID generated by requestIdMiddleware for every inbound request
 * - account / apiKey: set by apiKeyAuth for /v1/* routes (narrowed select)
 * - walletAddress: normalized 64-char address — set by identityAuth
 */
export type AppVariables = {
  requestId: string;
  /** Platform identity — always present on /v1/* after apiKeyAuth. */
  account: AuthedAccount;
  /** Billing identity — always present on /v1/* after apiKeyAuth. */
  apiClient: AuthedApiClient;
  apiKey: AuthedApiKey;
  walletAddress?: string;
  isAdmin?: boolean;
  /** Admin wallet from adminSignatureAuth — set when the signed-request path
   *  authorizes a request (attribution/audit). Absent on the master-key path. */
  adminWallet?: string;
};

/**
 * Full Hono Env type. Use as:
 *   new Hono<AppEnv>()
 *   MiddlewareHandler<AppEnv>
 */
export type AppEnv = { Variables: AppVariables };
